#!/usr/bin/env python3
"""Write firmware/components/app_config/secrets.h with the OTA encryption key.

    python write_secrets.py --generate            new random key (local use)
    python write_secrets.py --from-env NAME       key from an environment variable (CI)

Prints only the path and the key fingerprint, never the key. Back the key up
from the generated file into a password manager (see docs/release/keys.md).
"""

import argparse
import secrets
import sys
from pathlib import Path

import ota_crypto

DEFAULT_OUTPUT = Path(__file__).resolve().parent.parent / "components" / "app_config" / "secrets.h"

TEMPLATE = """#pragma once
// OTA encryption key (AES-256, 64 hex characters).
// Generated by firmware/scripts/write_secrets.py. DO NOT COMMIT: it is gitignored.
// Losing this key means boards using it cannot accept encrypted OTA images.
#define APP_CONFIG_OTA_ENCRYPTION_KEY "{key}"
"""


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = ap.add_mutually_exclusive_group(required=True)
    group.add_argument("--generate", action="store_true")
    group.add_argument("--from-env", metavar="NAME")
    ap.add_argument("--output", default=str(DEFAULT_OUTPUT))
    ap.add_argument("--force", action="store_true", help="overwrite an existing secrets.h")
    args = ap.parse_args(argv)

    out = Path(args.output)
    try:
        if args.generate:
            key = secrets.token_hex(32)
        else:
            key = ota_crypto.read_key(args.from_env, None)
        if ota_crypto.is_zero_key(key):
            raise ValueError("refusing the all-zero key (that is the unconfigured dev key)")
        if out.exists() and not args.force:
            raise ValueError(f"{out} already exists; use --force to replace it (the old key would be lost)")
        out.parent.mkdir(parents=True, exist_ok=True)
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(TEMPLATE.format(key=key))
    except (ValueError, OSError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    print(f"wrote {out}")
    print(f"key fingerprint: {ota_crypto.key_fingerprint(key)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
