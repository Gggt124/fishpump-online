/* Shared guard for JSON write endpoints: auth, same origin, JSON object body
 * read into the caller's buffer. Returns NULL after sending the error
 * response. An empty body becomes {}. The parsed tree owns its own memory. */
static cJSON *api_begin_json_post(httpd_req_t *req, char *body,
                                  size_t body_size, esp_err_t *sent) {
  if (!require_auth(req)) {
    *sent = send_json(req, "{\"ok\":false,\"error\":\"unauthorized\"}",
                      "401 Unauthorized");
    return NULL;
  }
  if (!is_same_origin(req, false)) {
    *sent = send_api_error(req, "forbidden", "Cross-origin write blocked",
                           "403 Forbidden");
    return NULL;
  }
  body[0] = '\0';
  if (req->content_len == 0) {
    strcpy(body, "{}");
  } else if (!read_request_body(req, body, body_size)) {
    *sent = send_api_error(req, "invalid_body", "Request body is missing or too large",
                           "400 Bad Request");
    return NULL;
  }
  cJSON *root = cJSON_Parse(body);
  if (!root || !cJSON_IsObject(root)) {
    cJSON_Delete(root);
    *sent = send_api_error(req, "invalid_json", "Expected a JSON object",
                           "400 Bad Request");
    return NULL;
  }
  return root;
}

