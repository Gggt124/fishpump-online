/* POST /api/display/config - protected, save new display idle dim setting */
static esp_err_t handle_api_display_config_post(httpd_req_t *req) {
  if (!require_auth(req)) {
    return send_json(req, "{\"ok\":false,\"error\":\"unauthorized\"}",
                     "401 Unauthorized");
  }

  if (!is_same_origin(req, false)) {
    return send_api_error(req, "forbidden",
                          "Cross-origin display config save blocked",
                          "403 Forbidden");
  }

  char body[128] = {0};
  if (!read_request_body(req, body, sizeof(body))) {
    return send_api_error(req, "empty_body", "Request body is required",
                          "400 Bad Request");
  }

  cJSON *root = cJSON_Parse(body);
  if (!root || !cJSON_IsObject(root)) {
    if (root)
      cJSON_Delete(root);
    return send_api_error(req, "invalid_json", "Expected a JSON object",
                          "400 Bad Request");
  }

  cJSON *dim_item = cJSON_GetObjectItemCaseSensitive(root, "dim_percent");
  if (!cJSON_IsNumber(dim_item) || dim_item->valueint < 0 ||
      dim_item->valueint > 100) {
    cJSON_Delete(root);
    return send_api_error(req, "invalid_parameter",
                          "dim_percent must be an integer between 0 and 100",
                          "400 Bad Request");
  }

  cJSON *save_item = cJSON_GetObjectItemCaseSensitive(root, "save");
  bool do_save = true;
  if (cJSON_IsBool(save_item)) {
    do_save = cJSON_IsTrue(save_item);
  }

  uint8_t new_dim = (uint8_t)dim_item->valueint;
  cJSON_Delete(root);

  if (do_save) {
    if (!nvs_store_save_display_settings(new_dim)) {
      ESP_LOGE(TAG, "Failed to save display settings to NVS");
      return send_api_error(req, "save_failed", "Failed to save to NVS",
                            "500 Internal Server Error");
    }
  }

  tft_display_set_idle_dim_percent(new_dim);

  /* A9 UX: Preview the new dim setting immediately instead of waking to 100%.
   */
  tft_display_set_brightness(new_dim);

  return send_json(req, "{\"ok\":true}", "200 OK");
}

typedef struct {
  char *payload;
  size_t len;
} sse_work_item_t;

static void sse_broadcast_work(void *arg) {
  sse_work_item_t *item = (sse_work_item_t *)arg;
  if (!item) {
    return;
  }

  if (s_server && item->payload && item->len > 0) {
    int clients[SSE_MAX_CLIENTS];
    taskENTER_CRITICAL(&s_sse_client_lock);
    memcpy(clients, s_sse_clients, sizeof(clients));
    taskEXIT_CRITICAL(&s_sse_client_lock);

    char chunk_header[16];
    int header_len = snprintf(chunk_header, sizeof(chunk_header), "%x\r\n",
                              (unsigned int)item->len);

    for (size_t i = 0; i < SSE_MAX_CLIENTS; i++) {
      if (clients[i] >= 0) {
        int ret1 = httpd_socket_send(s_server, clients[i], chunk_header,
                                     header_len, 0);
        int ret2 = httpd_socket_send(s_server, clients[i], item->payload,
                                     item->len, 0);
        int ret3 = httpd_socket_send(s_server, clients[i], "\r\n", 2, 0);

        if (ret1 < 0 || ret2 < 0 || ret3 < 0) {
          ESP_LOGW(TAG, "SSE send failed on fd=%d (client disconnected)",
                   clients[i]);
          sse_unregister_client(clients[i]);
        }
      }
    }
  }

  if (item->payload) {
    free(item->payload);
  }
  free(item);
}

static void web_server_telemetry_cb(const telemetry_event_t *event,
                                    void *user_ctx) {
  (void)user_ctx;
  if (!event || !s_server) {
    return;
  }

  if (sse_active_client_count() == 0) {
    return;
  }

  char json_buf[256];
  const char *evt_name = "unknown";

  switch (event->type) {
  case TELEMETRY_EVT_PUMP:
    evt_name = "pump";
    snprintf(json_buf, sizeof(json_buf),
             "{\"active_pump\":%u,\"is_running\":%s,\"elapsed_sec\":%lu,"
             "\"remaining_sec\":%lu,\"relay1\":%s,\"relay2\":%s}",
             event->data.pump.active_pump,
             event->data.pump.is_running ? "true" : "false",
             (unsigned long)event->data.pump.elapsed_sec,
             (unsigned long)event->data.pump.remaining_sec,
             event->data.pump.relay_1_active ? "true" : "false",
             event->data.pump.relay_2_active ? "true" : "false");
    break;

  case TELEMETRY_EVT_FLOAT:
    evt_name = "float";
    snprintf(json_buf, sizeof(json_buf), "{\"float_is_high\":%s}",
             event->data.float_state.float_is_high ? "true" : "false");
    break;

  case TELEMETRY_EVT_COOLING:
    evt_name = "cooling";
    snprintf(json_buf, sizeof(json_buf),
             "{\"temp_c\":%.2f,\"valid\":%s,\"relay\":%s,\"lockout_sec\":%lu}",
             event->data.cooling.current_temp_c,
             event->data.cooling.is_sensor_valid ? "true" : "false",
             event->data.cooling.cooling_relay_active ? "true" : "false",
             (unsigned long)event->data.cooling.lockout_remaining_sec);
    break;

  case TELEMETRY_EVT_HEALTH:
    evt_name = "health";
    snprintf(json_buf, sizeof(json_buf),
             "{\"free_heap\":%lu,\"free_psram\":%lu,\"rssi\":%d,\"uptime_sec\":%lu,"
             "\"oom_strikes\":%u}",
             (unsigned long)event->data.health.free_heap_bytes,
             (unsigned long)event->data.health.free_psram_bytes,
             event->data.health.wifi_rssi,
             (unsigned long)event->data.health.uptime_sec,
             event->data.health.oom_strikes);
    break;

  default:
    return;
  }

  char sse_packet[384];
  int sse_len = snprintf(sse_packet, sizeof(sse_packet),
                         "event: %s\ndata: %s\n\n", evt_name, json_buf);
  if (sse_len <= 0 || sse_len >= sizeof(sse_packet)) {
    return;
  }

  sse_work_item_t *work = malloc(sizeof(sse_work_item_t));
  if (!work) {
    return;
  }
  work->payload = strdup(sse_packet);
  if (!work->payload) {
    free(work);
    return;
  }
  work->len = (size_t)sse_len;

  if (httpd_queue_work(s_server, sse_broadcast_work, work) != ESP_OK) {
    free(work->payload);
    free(work);
  }
}

static esp_err_t handle_api_events(httpd_req_t *req) {
  int sockfd = httpd_req_to_sockfd(req);
  if (sockfd < 0) {
    return ESP_FAIL;
  }

  if (!sse_register_client(sockfd)) {
    ESP_LOGW(TAG, "SSE client rejected on fd=%d: max SSE clients (%d) reached",
             sockfd, SSE_MAX_CLIENTS);
    httpd_resp_set_status(req, "503 Service Unavailable");
    httpd_resp_set_type(req, "application/json");
    return httpd_resp_send(req, "{\"ok\":false,\"error\":\"sse_clients_full\"}",
                           HTTPD_RESP_USE_STRLEN);
  }

  httpd_resp_set_type(req, "text/event-stream");
  httpd_resp_set_hdr(req, "Cache-Control", "no-cache, no-transform");
  httpd_resp_set_hdr(req, "Connection", "keep-alive");
  httpd_resp_set_hdr(req, "Access-Control-Allow-Origin", "*");

  const char *init_msg = "event: connected\ndata: {\"status\":\"ok\"}\n\n";
  if (httpd_resp_send_chunk(req, init_msg, strlen(init_msg)) != ESP_OK) {
    sse_unregister_client(sockfd);
    return ESP_FAIL;
  }

  ESP_LOGI(TAG, "SSE client registered on fd=%d (%u/%d active)", sockfd,
           (unsigned int)sse_active_client_count(), SSE_MAX_CLIENTS);
  return ESP_OK;
}

