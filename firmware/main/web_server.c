static esp_err_t api_cooling_send_config(
    httpd_req_t *req, const nvs_store_cooling_settings_t *settings,
    nvs_store_cooling_settings_load_status_t status, bool include_status) {
  cJSON *root = cJSON_CreateObject();
  if (!root) {
    return send_api_error(req, "memory", "JSON allocation failed",
                          "500 Internal Server Error");
  }

  cJSON_AddBoolToObject(root, "ok", true);
  api_cooling_add_config_fields(root, settings, status);
  api_cooling_add_limits(root);
  if (include_status) {
    cJSON *status_obj = cJSON_AddObjectToObject(root, "status");
    if (!status_obj || !api_cooling_add_status_fields(status_obj)) {
      cJSON_Delete(root);
      return send_api_error(req, "status_unavailable",
                            "Cooling status is unavailable", "409 Conflict");
    }
  }

  char *json_str = cJSON_PrintUnformatted(root);
  cJSON_Delete(root);
  if (!json_str) {
    return send_api_error(req, "memory", "JSON allocation failed",
                          "500 Internal Server Error");
  }

  esp_err_t result = send_json(req, json_str, "200 OK");
  free(json_str);
  return result;
}

