static esp_err_t handle_instrumented_route(httpd_req_t *req) {
  wifi_manager_reset_ap_timeout();
  web_route_diag_t *route = (web_route_diag_t *)req->user_ctx;
  if (!route || !route->handler) {
    ESP_LOGE(TAG, "[HTTP_REQ] missing route context uri=%s fd=%d", req->uri,
             httpd_req_to_sockfd(req));
    return ESP_FAIL;
  }

  int64_t start_ms = esp_timer_get_time() / 1000;
  /* Touch alive timestamp: prevents false-positive HTTP_HUNG during
   * legitimate slow handlers. The health-check work is queued-based
   * and only runs when httpd task is idle; this ensures the clock
   * resets when a handler starts, not only when the queue drains. */
  s_httpd_last_alive_ms = (uint32_t)start_ms;
  taskENTER_CRITICAL(&s_web_diag_lock);
  s_web_diag.requests_started++;
  s_web_diag.active_handlers++;
  if (s_web_diag.active_handlers > s_web_diag.peak_active_handlers) {
    s_web_diag.peak_active_handlers = s_web_diag.active_handlers;
  }
  taskEXIT_CRITICAL(&s_web_diag_lock);

  if (route->method == HTTP_POST) {
    /* Do not wake screen for config/preview adjustments */
    if (strcmp(route->uri, "/api/display/config") != 0) {
      tft_display_reset_idle_timer();
    }
  }

  esp_err_t result = route->handler(req);
  uint32_t duration_ms = (uint32_t)((esp_timer_get_time() / 1000) - start_ms);
  UBaseType_t stack_hwm = uxTaskGetStackHighWaterMark(NULL);
  bool failed = result != ESP_OK;
  bool slow = duration_ms >= APP_TEMPLATE_HTTP_SLOW_REQUEST_MS;

  taskENTER_CRITICAL(&s_web_diag_lock);
  route->requests++;
  if (failed) {
    route->failures++;
  }
  if (slow) {
    route->slow_requests++;
  }
  if (duration_ms > route->max_duration_ms) {
    route->max_duration_ms = duration_ms;
  }
  s_web_diag.requests_completed++;
  if (failed) {
    s_web_diag.requests_failed++;
  }
  if (slow) {
    s_web_diag.slow_requests++;
  }
  if (s_web_diag.active_handlers > 0) {
    s_web_diag.active_handlers--;
  }
  if (s_web_diag.handler_stack_hwm_min == 0 ||
      stack_hwm < s_web_diag.handler_stack_hwm_min) {
    s_web_diag.handler_stack_hwm_min = stack_hwm;
  }
  taskEXIT_CRITICAL(&s_web_diag_lock);

  if (failed || slow) {
    ESP_LOGW(TAG,
             "[HTTP_REQ] method=%s uri=%s fd=%d duration_ms=%lu result=%s "
             "heap=%lu stack_hwm=%lu",
             http_method_name(route->method), route->uri,
             httpd_req_to_sockfd(req), (unsigned long)duration_ms,
             esp_err_to_name(result), (unsigned long)esp_get_free_heap_size(),
             (unsigned long)stack_hwm);
  }
  return result;
}

void web_server_log_diagnostics(void) {
  web_server_diag_t diag;
  uint32_t json_send_failures;
  uint32_t static_send_failures;
  uint32_t static_cache_hits;
  uint32_t static_deadline_aborts;

  taskENTER_CRITICAL(&s_web_diag_lock);
  diag = s_web_diag;
  json_send_failures = s_json_send_failures;
  static_send_failures = s_static_send_failures;
  static_cache_hits = s_static_cache_hits;
  static_deadline_aborts = s_static_deadline_aborts;
  taskEXIT_CRITICAL(&s_web_diag_lock);

  ESP_LOGI(
      TAG,
      "[HTTP_DIAG] server=%s starts=%lu failures=%lu route_reg_fail=%lu "
      "sockets_active=%lu opened=%lu closed=%lu peak=%lu requests_started=%lu "
      "completed=%lu failed=%lu slow=%lu handlers_active=%lu peak=%lu "
      "stack_hwm_min=%lu json_send_fail=%lu static_send_fail=%lu "
      "static_cache_hits=%lu static_deadline_aborts=%lu heap=%lu heap_min=%lu "
      "largest=%lu",
      s_server ? "up" : "down", (unsigned long)diag.server_start_attempts,
      (unsigned long)diag.server_start_failures,
      (unsigned long)diag.route_registration_failures,
      (unsigned long)diag.active_sessions, (unsigned long)diag.sessions_opened,
      (unsigned long)diag.sessions_closed,
      (unsigned long)diag.peak_active_sessions,
      (unsigned long)diag.requests_started,
      (unsigned long)diag.requests_completed,
      (unsigned long)diag.requests_failed, (unsigned long)diag.slow_requests,
      (unsigned long)diag.active_handlers,
      (unsigned long)diag.peak_active_handlers,
      (unsigned long)diag.handler_stack_hwm_min,
      (unsigned long)json_send_failures, (unsigned long)static_send_failures,
      (unsigned long)static_cache_hits, (unsigned long)static_deadline_aborts,
      (unsigned long)esp_get_free_heap_size(),
      (unsigned long)esp_get_minimum_free_heap_size(),
      (unsigned long)heap_caps_get_largest_free_block(MALLOC_CAP_INTERNAL));

  for (size_t i = 0; i < sizeof(s_routes) / sizeof(s_routes[0]); i++) {
    taskENTER_CRITICAL(&s_web_diag_lock);
    uint32_t delta_requests =
        s_routes[i].requests - s_routes[i].reported_requests;
    uint32_t requests = s_routes[i].requests;
    uint32_t failures = s_routes[i].failures;
    uint32_t slow_requests = s_routes[i].slow_requests;
    uint32_t max_duration_ms = s_routes[i].max_duration_ms;
    s_routes[i].reported_requests = s_routes[i].requests;
    taskEXIT_CRITICAL(&s_web_diag_lock);

    if (delta_requests > 0) {
      ESP_LOGI(TAG,
               "[HTTP_ROUTE] method=%s uri=%s delta=%lu total=%lu failed=%lu "
               "slow=%lu max_ms=%lu",
               http_method_name(s_routes[i].method), s_routes[i].uri,
               (unsigned long)delta_requests, (unsigned long)requests,
               (unsigned long)failures, (unsigned long)slow_requests,
               (unsigned long)max_duration_ms);
    }
  }
}

