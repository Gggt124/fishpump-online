static void url_decode(char *dst, const char *src) {
  while (*src) {
    if (*src == '+') {
      *dst++ = ' ';
      src++;
    } else if (*src == '%' && src[1] && src[2]) {
      char hex[3] = {src[1], src[2], '\0'};
      *dst++ = (char)strtol(hex, NULL, 16);
      src += 3;
    } else {
      *dst++ = *src++;
    }
  }
  *dst = '\0';
}

static void get_client_ip(httpd_req_t *req, char *ipstr, size_t ipstr_len) {
  ipstr[0] = '\0';
  int sockfd = httpd_req_to_sockfd(req);
  struct sockaddr_in6 addr;
  socklen_t addr_size = sizeof(addr);
  if (getpeername(sockfd, (struct sockaddr *)&addr, &addr_size) == 0) {
    if (addr.sin6_family == AF_INET) {
      struct sockaddr_in *addr4 = (struct sockaddr_in *)&addr;
      inet_ntop(AF_INET, &addr4->sin_addr, ipstr, ipstr_len);
    } else if (addr.sin6_family == AF_INET6) {
      inet_ntop(AF_INET6, &addr.sin6_addr, ipstr, ipstr_len);
    }
  }
}

/* Extract session token from Cookie header.
   WARNING: This is a local-prototype auth scheme.
   Session tokens are random but transmitted as plain cookies.
   Not secure against network sniffing on open Wi-Fi. */
static bool get_session_from_request(httpd_req_t *req, char *token_out,
                                     size_t token_len) {
  size_t buf_len = httpd_req_get_hdr_value_len(req, "Cookie");
  if (buf_len <= 0)
    return false;

  char *cookie_buf = malloc(buf_len + 1);
  if (!cookie_buf)
    return false;

  if (httpd_req_get_hdr_value_str(req, "Cookie", cookie_buf, buf_len + 1) !=
      ESP_OK) {
    free(cookie_buf);
    return false;
  }

  /* Simple parse: find "session=" */
  const char *start = cookie_buf;
  while ((start = strstr(start, "session=")) != NULL) {
    if (start == cookie_buf || *(start - 1) == ' ' || *(start - 1) == ';') {
      start += 8; /* skip "session=" */
      const char *end = strchr(start, ';');
      size_t len = end ? (size_t)(end - start) : strlen(start);
      if (len >= token_len)
        len = token_len - 1;
      memcpy(token_out, start, len);
      token_out[len] = '\0';
      free(cookie_buf);
      return true;
    }
    start += 8;
  }
  free(cookie_buf);
  return false;
}

/* Auth check middleware - returns true if session is valid */
static bool require_auth(httpd_req_t *req) {
  char token[SESSION_TOKEN_LEN] = {0};
  if (!get_session_from_request(req, token, sizeof(token))) {
    ESP_LOGW(TAG, "AUTH: no session cookie in request uri=%s", req->uri);
    return false;
  }
  char client_ip[64] = {0};
  get_client_ip(req, client_ip, sizeof(client_ip));
  bool valid = session_validate(token, client_ip);
  if (!valid) {
    ESP_LOGW(TAG, "AUTH: session invalid uri=%s ip='%s' token_len=%d", req->uri,
             client_ip, (int)strlen(token));
  }
  return valid;
}

static bool host_equals(const char *host_start, size_t host_len,
                        const char *expected) {
  return expected && strlen(expected) == host_len &&
         strncmp(host_start, expected, host_len) == 0;
}

static bool header_matches_allowed_origin(const char *header) {
  if (!header || !header[0]) {
    return false;
  }

  const char *host_start = strstr(header, "://");
  host_start = host_start ? host_start + 3 : header;

  const char *host_end = host_start;
  while (*host_end && *host_end != ':' && *host_end != '/' &&
         *host_end != '?' && *host_end != '#') {
    host_end++;
  }

  size_t host_len = (size_t)(host_end - host_start);
  if (host_len == 0) {
    return false;
  }

  const char *ap_ip = wifi_manager_get_ap_ip();
  if (host_equals(host_start, host_len, ap_ip)) {
    return true;
  }

  const char *sta_ip = wifi_manager_get_sta_ip();
  if (sta_ip && sta_ip[0] && host_equals(host_start, host_len, sta_ip)) {
    return true;
  }

  return host_equals(host_start, host_len, APP_TEMPLATE_MDNS_HOSTNAME ".local");
}

/* Check Origin/Referer to prevent cross-site POST (CSRF mitigation) */
static bool is_same_origin(httpd_req_t *req, bool allow_missing_header) {
  size_t origin_len = httpd_req_get_hdr_value_len(req, "Origin");
  size_t referer_len = httpd_req_get_hdr_value_len(req, "Referer");
  char buf[128] = {0};

  if (origin_len > 0) {
    if (origin_len >= sizeof(buf))
      return false;
    httpd_req_get_hdr_value_str(req, "Origin", buf, sizeof(buf));
  } else if (referer_len > 0) {
    if (referer_len >= sizeof(buf))
      return false;
    httpd_req_get_hdr_value_str(req, "Referer", buf, sizeof(buf));
  } else {
    ESP_LOGW(TAG, "POST request without Origin/Referer header");
    return allow_missing_header;
  }

  if (header_matches_allowed_origin(buf))
    return true;

  ESP_LOGW(TAG, "Cross-origin POST blocked: %s", buf);
  return false;
}

static bool read_request_body(httpd_req_t *req, char *body, size_t body_size) {
  if (!req || !body || body_size == 0 || req->content_len == 0 ||
      req->content_len >= body_size) {
    return false;
  }

  size_t received = 0;
  int timeout_count = 0;
  while (received < req->content_len) {
    int ret = httpd_req_recv(req, body + received, req->content_len - received);
    if (ret == HTTPD_SOCK_ERR_TIMEOUT) {
      if (++timeout_count >= 3) {
        return false;
      }
      continue;
    }
    if (ret <= 0) {
      return false;
    }
    timeout_count = 0;
    received += (size_t)ret;
  }

  body[received] = '\0';
  return true;
}

/* Send JSON response */
static esp_err_t send_json(httpd_req_t *req, const char *json,
                           const char *status) {
  set_no_store_response_headers(req);
  httpd_resp_set_type(req, "application/json");
  httpd_resp_set_status(req, status);
  esp_err_t ret = httpd_resp_send(req, json, strlen(json));
  if (ret != ESP_OK) {
    uint32_t failure_count = increment_json_send_failures();
    ESP_LOGW(TAG, "JSON response send failed: uri=%s fd=%d err=%s count=%lu",
             req->uri, httpd_req_to_sockfd(req), esp_err_to_name(ret),
             (unsigned long)failure_count);
    return ret;
  }
  return ret;
}

static esp_err_t send_api_error(httpd_req_t *req, const char *code,
                                const char *message, const char *status) {
  cJSON *root = cJSON_CreateObject();
  if (!root) {
    return send_json(req,
                     "{\"ok\":false,\"error\":\"memory\",\"message\":\"JSON "
                     "allocation failed\"}",
                     "500 Internal Server Error");
  }

  cJSON_AddBoolToObject(root, "ok", false);
  cJSON_AddStringToObject(root, "error", code);
  cJSON_AddStringToObject(root, "message", message);

  char *json_str = cJSON_PrintUnformatted(root);
  cJSON_Delete(root);
  if (!json_str) {
    return send_json(req,
                     "{\"ok\":false,\"error\":\"memory\",\"message\":\"JSON "
                     "allocation failed\"}",
                     "500 Internal Server Error");
  }

  esp_err_t result = send_json(req, json_str, status);
  free(json_str);
  return result;
}


static bool __attribute__((unused)) api_pump_required_u32(const cJSON *root, const char *name,
                                  uint32_t *out, const char **error_code,
                                  const char **error_message) {
  const cJSON *item = cJSON_GetObjectItem(root, name);
  if (!item) {
    *error_code = "missing_field";
    *error_message = name;
    return false;
  }
  if (!cJSON_IsNumber(item) || !(item->valuedouble >= 0.0)) {
    *error_code = "invalid_type";
    *error_message = name;
    return false;
  }
  if (item->valuedouble < (double)APP_TEMPLATE_PUMP_TIMER_MIN_SEC ||
      item->valuedouble > (double)APP_TEMPLATE_PUMP_TIMER_MAX_SEC) {
    *error_code = "duration_out_of_range";
    *error_message = name;
    return false;
  }

  uint32_t value = (uint32_t)item->valuedouble;
  if ((double)value != item->valuedouble) {
    *error_code = "invalid_type";
    *error_message = name;
    return false;
  }

  *out = value;
  return true;
}

static bool __attribute__((unused)) api_pump_required_bool(const cJSON *root, const char *name,
                                   bool *out, const char **error_code,
                                   const char **error_message) {
  const cJSON *item = cJSON_GetObjectItem(root, name);
  if (!item) {
    *error_code = "missing_field";
    *error_message = name;
    return false;
  }
  if (!cJSON_IsBool(item)) {
    *error_code = "invalid_type";
    *error_message = name;
    return false;
  }

  *out = cJSON_IsTrue(item);
  return true;
}

