static void httpd_health_check_work(void *arg) {
  (void)arg;
  s_httpd_last_alive_ms = (uint32_t)(esp_timer_get_time() / 1000);
}

bool web_server_queue_health_check(void) {
  if (s_server) {
    return (httpd_queue_work(s_server, httpd_health_check_work, NULL) ==
            ESP_OK);
  }
  return true;
}

bool web_server_check_health(uint32_t timeout_ms, uint32_t *out_staleness_ms) {
  if (!s_server) {
    if (out_staleness_ms) {
      *out_staleness_ms = 0;
    }
    return true; // Not started yet, ignore
  }
  uint32_t now_ms = (uint32_t)(esp_timer_get_time() / 1000);
  uint32_t staleness = now_ms - s_httpd_last_alive_ms;
  if (out_staleness_ms) {
    *out_staleness_ms = staleness;
  }
  return staleness <= timeout_ms;
}

bool web_server_start(void) {
  /* --- One-time resource allocation (safe here: task context, no ISR) --- */
  if (s_login_rate_limit_mutex == NULL) {
    s_login_rate_limit_mutex = xSemaphoreCreateMutex();
    configASSERT(s_login_rate_limit_mutex != NULL);
  }
  if (s_password_state_mutex == NULL) {
    s_password_state_mutex = xSemaphoreCreateMutex();
    configASSERT(s_password_state_mutex != NULL);
  }

  if (s_server) {
    return true;
  }

  taskENTER_CRITICAL(&s_sse_client_lock);
  for (size_t i = 0; i < SSE_MAX_CLIENTS; i++) {
    s_sse_clients[i] = -1;
  }
  taskEXIT_CRITICAL(&s_sse_client_lock);

  taskENTER_CRITICAL(&s_web_diag_lock);
  s_web_diag.server_start_attempts++;
  taskEXIT_CRITICAL(&s_web_diag_lock);

  httpd_config_t config = HTTPD_DEFAULT_CONFIG();
  size_t route_count = sizeof(s_routes) / sizeof(s_routes[0]);
  config.max_uri_handlers = (uint16_t)(route_count + 8);
  if (config.max_uri_handlers < APP_TEMPLATE_HTTP_MAX_URI_HANDLERS) {
    config.max_uri_handlers = APP_TEMPLATE_HTTP_MAX_URI_HANDLERS;
  }
  config.core_id = 0; /* Pinned to Core 0 */
  config.max_open_sockets = APP_TEMPLATE_HTTP_MAX_OPEN_SOCKETS;
  config.backlog_conn = 5; /* reduced to match lower max_open_sockets */
  config.recv_wait_timeout = APP_TEMPLATE_HTTP_RECV_TIMEOUT_SEC;
  config.send_wait_timeout = APP_TEMPLATE_HTTP_SEND_TIMEOUT_SEC;
  config.lru_purge_enable = true;
  config.stack_size = 8192; /* A7 audit: handlers allocate large on-stack
                               structs; 4096 default insufficient */
  config.keep_alive_enable = true;
  config.keep_alive_idle = APP_TEMPLATE_HTTP_KEEP_ALIVE_IDLE_SEC;
  config.keep_alive_interval = APP_TEMPLATE_HTTP_KEEP_ALIVE_INTERVAL_SEC;
  config.keep_alive_count = APP_TEMPLATE_HTTP_KEEP_ALIVE_COUNT;
  config.open_fn = diagnostics_socket_open;
  config.close_fn = diagnostics_socket_close;

  esp_err_t start_err = httpd_start(&s_server, &config);
  if (start_err != ESP_OK) {
    taskENTER_CRITICAL(&s_web_diag_lock);
    s_web_diag.server_start_failures++;
    taskEXIT_CRITICAL(&s_web_diag_lock);
    ESP_LOGE(TAG, "Failed to start HTTP server: %s",
             esp_err_to_name(start_err));
    s_server = NULL;
    return false;
  }

  s_httpd_last_alive_ms = (uint32_t)(esp_timer_get_time() / 1000);

  static bool s_telemetry_subscribed = false;
  if (!s_telemetry_subscribed) {
    esp_err_t sub_err = telemetry_hub_subscribe(web_server_telemetry_cb, NULL);
    if (sub_err == ESP_OK) {
      s_telemetry_subscribed = true;
      ESP_LOGI(TAG, "Subscribed to telemetry_hub for SSE streaming");
    } else {
      ESP_LOGW(TAG, "Failed to subscribe to telemetry_hub: %s",
               esp_err_to_name(sub_err));
    }
  }

  /* Register global 404 handler for captive portal routing of random domains */
  httpd_register_err_handler(s_server, HTTPD_404_NOT_FOUND,
                             captive_portal_404_handler);

  bool route_registration_failed = false;
  for (size_t i = 0; i < sizeof(s_routes) / sizeof(s_routes[0]); i++) {
    const httpd_uri_t route = {
        .uri = s_routes[i].uri,
        .method = s_routes[i].method,
        .handler = handle_instrumented_route,
        .user_ctx = &s_routes[i],
    };
    esp_err_t err = httpd_register_uri_handler(s_server, &route);
    if (err != ESP_OK) {
      taskENTER_CRITICAL(&s_web_diag_lock);
      s_web_diag.route_registration_failures++;
      taskEXIT_CRITICAL(&s_web_diag_lock);
      ESP_LOGE(TAG, "Failed to register route %s: %s", s_routes[i].uri,
               esp_err_to_name(err));
      route_registration_failed = true;
    }
  }

  if (route_registration_failed) {
    ESP_LOGE(
        TAG,
        "HTTP server route registration incomplete; stopping server for retry");
    httpd_stop(s_server);
    s_server = NULL;
    return false;
  }

  ESP_LOGI(TAG,
           "HTTP server started on port %d (max_sockets=%d, recv_timeout=%d, "
           "send_timeout=%d, tcp_keepalive=%s)",
           config.server_port, config.max_open_sockets,
           config.recv_wait_timeout, config.send_wait_timeout,
           config.keep_alive_enable ? "true" : "false");
  return true;
}
