static void delayed_reboot_task(void *pvParameters) {
  (void)pvParameters;
  vTaskDelay(pdMS_TO_TICKS(3000));
  ESP_LOGI(TAG, "Executing scheduled reboot...");
  esp_restart();
  vTaskDelete(NULL);
}

static void schedule_delayed_reboot(void) {
  taskENTER_CRITICAL(&s_reboot_lock);
  if (s_reboot_scheduled) {
    taskEXIT_CRITICAL(&s_reboot_lock);
    ESP_LOGW(TAG, "Reboot already scheduled — ignoring duplicate request");
    return;
  }
  s_reboot_scheduled = true;
  taskEXIT_CRITICAL(&s_reboot_lock);
  xTaskCreate(delayed_reboot_task, "delayed_reboot", 2048, NULL,
              tskIDLE_PRIORITY + 1, NULL);
}

/* POST /api/auth/credentials */
static esp_err_t handle_api_auth_credentials(httpd_req_t *req) {
  if (!require_auth(req)) {
    return send_json(req, "{\"ok\":false,\"error\":\"unauthorized\"}",
                     "401 Unauthorized");
  }
  if (!is_same_origin(req, false)) {
    return send_json(req, "{\"ok\":false,\"error\":\"forbidden\"}",
                     "403 Forbidden");
  }

  char body[512] = {0};
  if (req->content_len >= sizeof(body)) {
    return send_json(req, "{\"ok\":false,\"error\":\"payload_too_large\"}",
                     "413 Request Entity Too Large");
  }
  if (!read_request_body(req, body, sizeof(body))) {
    return send_json(req, "{\"ok\":false,\"error\":\"empty_body\"}",
                     "400 Bad Request");
  }

  cJSON *root = cJSON_Parse(body);
  if (!root) {
    return send_json(req, "{\"ok\":false,\"error\":\"invalid_json\"}",
                     "400 Bad Request");
  }

  cJSON *n = cJSON_GetObjectItem(root, "nonce");
  cJSON *cp = cJSON_GetObjectItem(root, "current_password");
  cJSON *nu = cJSON_GetObjectItem(root, "new_username");
  cJSON *np = cJSON_GetObjectItem(root, "new_password");

  if (!n || !cJSON_IsString(n) || !cp || !cJSON_IsString(cp) || !np ||
      !cJSON_IsString(np)) {
    cJSON_Delete(root);
    return send_json(req, "{\"ok\":false,\"error\":\"missing_fields\"}",
                     "400 Bad Request");
  }

  if (s_auth_nonce[0] == '\0' || strcmp(n->valuestring, s_auth_nonce) != 0) {
    s_auth_nonce[0] = '\0';
    cJSON_Delete(root);
    return send_json(req, "{\"ok\":false,\"error\":\"invalid_nonce\"}",
                     "400 Bad Request");
  }
  s_auth_nonce[0] = '\0'; // prevent replay

  char stored_user[64] = {0};
  char stored_pass[64] = {0};
  nvs_store_get_credentials(stored_user, sizeof(stored_user), stored_pass,
                            sizeof(stored_pass));

  if (strcmp(cp->valuestring, stored_pass) != 0) {
    cJSON_Delete(root);
    return send_json(req, "{\"ok\":false,\"error\":\"invalid_credentials\"}",
                     "400 Bad Request");
  }

  const char *new_user_str =
      (nu && cJSON_IsString(nu) && strlen(nu->valuestring) > 0)
          ? nu->valuestring
          : stored_user;
  const char *new_pass_str = np->valuestring;

  if (strcmp(new_pass_str, APP_TEMPLATE_DEFAULT_PASSWORD) == 0) {
    cJSON_Delete(root);
    return send_json(req, "{\"ok\":false,\"error\":\"cannot_use_default\"}",
                     "400 Bad Request");
  }

  if (!is_valid_utf8_printable(new_user_str, 64) ||
      !is_valid_utf8_printable(new_pass_str, 64)) {
    cJSON_Delete(root);
    return send_json(req, "{\"ok\":false,\"error\":\"invalid_input\"}",
                     "400 Bad Request");
  }

  if (!nvs_store_stage_creds(new_user_str, new_pass_str)) {
    cJSON_Delete(root);
    return send_json(req, "{\"ok\":false,\"error\":\"store_failed\"}",
                     "500 Internal Server Error");
  }

  cJSON_Delete(root);
  nvs_store_set_restart_detail("CRED_CHANGE");
  schedule_delayed_reboot();
  return send_json(req, "{\"ok\":true,\"reboot_pending\":true}", "200 OK");
}

