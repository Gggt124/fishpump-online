static bool s_is_password_default_cached = false;
static bool s_password_state_initialized = false;

/* POST /api/change-password */
static esp_err_t handle_api_change_password(httpd_req_t *req) {
  if (!require_auth(req)) {
    return send_json(req, "{\"ok\":false,\"error\":\"unauthorized\"}",
                     "401 Unauthorized");
  }
  if (!is_same_origin(req, true)) {
    return send_json(req, "{\"ok\":false,\"error\":\"forbidden\"}",
                     "403 Forbidden");
  }

  char body[256] = {0};
  if (req->content_len >= sizeof(body)) {
    return send_json(req, "{\"ok\":false,\"error\":\"payload_too_large\"}",
                     "413 Request Entity Too Large");
  }
  if (!read_request_body(req, body, sizeof(body))) {
    return send_json(req, "{\"ok\":false,\"error\":\"empty_body\"}",
                     "400 Bad Request");
  }

  char current_password[64] = {0};
  char new_password[64] = {0};

  cJSON *root = cJSON_Parse(body);
  if (root) {
    cJSON *curr = cJSON_GetObjectItem(root, "current_password");
    cJSON *newp = cJSON_GetObjectItem(root, "new_password");
    if (curr && cJSON_IsString(curr)) {
      strlcpy(current_password, curr->valuestring,
              sizeof(current_password));
    }
    if (newp && cJSON_IsString(newp)) {
      strlcpy(new_password, newp->valuestring, sizeof(new_password));
    }
    cJSON_Delete(root);
  }

  if (strlen(current_password) == 0 || strlen(new_password) < 8) {
    return send_json(req, "{\"ok\":false,\"error\":\"invalid_input\"}",
                     "400 Bad Request");
  }

  char stored_user[64] = {0};
  char stored_pass[64] = {0};
  nvs_store_get_credentials(stored_user, sizeof(stored_user), stored_pass,
                            sizeof(stored_pass));

  if (strcmp(current_password, stored_pass) != 0) {
    return send_json(req, "{\"ok\":false,\"error\":\"invalid_credentials\"}",
                     "401 Unauthorized");
  }

  if (strcmp(new_password, APP_TEMPLATE_DEFAULT_PASSWORD) == 0) {
    return send_json(req, "{\"ok\":false,\"error\":\"cannot_use_default\"}",
                     "400 Bad Request");
  }

  if (!nvs_store_set_credentials(stored_user, new_password)) {
    return send_json(req, "{\"ok\":false,\"error\":\"storage_error\"}",
                     "500 Internal Server Error");
  }

  if (s_password_state_mutex) {
    if (xSemaphoreTake(s_password_state_mutex, pdMS_TO_TICKS(500)) != pdTRUE) {
      ESP_LOGE(TAG, "[MUTEX] password_state timeout in change_password");
      return send_json(req, "{\"ok\":false,\"error\":\"server_busy\"}",
                       "503 Service Unavailable");
    }
  }
  s_is_password_default_cached = false;
  s_password_state_initialized = true;
  if (s_password_state_mutex) {
    xSemaphoreGive(s_password_state_mutex);
  }

  return send_json(req, "{\"ok\":true}", "200 OK");
}

#define LOGIN_LRU_SIZE 16

typedef struct {
  char ip[64];
  int attempts;
  int64_t block_until;
  int64_t last_seen;
} login_rate_limit_t;

static bool is_password_default(void) {
  if (s_password_state_mutex) {
    if (xSemaphoreTake(s_password_state_mutex, pdMS_TO_TICKS(500)) != pdTRUE) {
      ESP_LOGE(TAG, "[MUTEX] password_state timeout in is_password_default — "
                    "assuming not default");
      return false; /* fail-safe: assume password is NOT default (more
                       restrictive) */
    }
  }
  if (s_password_state_initialized) {
    bool result = s_is_password_default_cached;
    if (s_password_state_mutex) {
      xSemaphoreGive(s_password_state_mutex);
    }
    return result;
  }

  char stored_user[64] = {0};
  char stored_pass[64] = {0};
  if (!nvs_store_get_credentials(stored_user, sizeof(stored_user), stored_pass,
                                 sizeof(stored_pass))) {
    s_is_password_default_cached = false;
  } else {
    s_is_password_default_cached =
        (strcmp(stored_pass, APP_TEMPLATE_DEFAULT_PASSWORD) == 0);
  }
  s_password_state_initialized = true;
  bool result = s_is_password_default_cached;
  if (s_password_state_mutex) {
    xSemaphoreGive(s_password_state_mutex);
  }
  return result;
}

static login_rate_limit_t s_rate_limits[LOGIN_LRU_SIZE] = {0};

static void update_login_rate_limit(const char *ip, int64_t now,
                                    bool is_success) {
  if (s_login_rate_limit_mutex) {
    if (xSemaphoreTake(s_login_rate_limit_mutex, pdMS_TO_TICKS(500)) !=
        pdTRUE) {
      ESP_LOGE(TAG,
               "[MUTEX] login_rate_limit timeout in update — skipping update "
               "for ip=%s",
               ip);
      return; /* skip rate-limit update; caller sends response normally */
    }
  }
  int current_idx = -1;
  for (int i = 0; i < LOGIN_LRU_SIZE; i++) {
    if (s_rate_limits[i].ip[0] != '\0' &&
        strcmp(s_rate_limits[i].ip, ip) == 0) {
      current_idx = i;
      break;
    }
  }
  if (current_idx == -1 && !is_success) {
    int oldest_idx = 0;
    int64_t oldest_time = s_rate_limits[0].last_seen;
    for (int i = 0; i < LOGIN_LRU_SIZE; i++) {
      if (s_rate_limits[i].ip[0] == '\0') {
        oldest_idx = i;
        break;
      }
      if (s_rate_limits[i].last_seen < oldest_time) {
        oldest_time = s_rate_limits[i].last_seen;
        oldest_idx = i;
      }
    }
    current_idx = oldest_idx;
    strlcpy(s_rate_limits[current_idx].ip, ip,
            sizeof(s_rate_limits[current_idx].ip));
    s_rate_limits[current_idx].attempts = 0;
    s_rate_limits[current_idx].block_until = 0;
  }
  if (current_idx != -1) {
    s_rate_limits[current_idx].last_seen = now;
    if (is_success) {
      s_rate_limits[current_idx].attempts = 0;
      s_rate_limits[current_idx].block_until = 0;
    } else {
      s_rate_limits[current_idx].attempts++;
      if (s_rate_limits[current_idx].attempts >= RATE_LIMIT_MAX) {
        s_rate_limits[current_idx].block_until = now + RATE_LIMIT_WINDOW;
      }
    }
  }
  if (s_login_rate_limit_mutex) {
    xSemaphoreGive(s_login_rate_limit_mutex);
  }
}

/* POST /api/login */
static esp_err_t handle_api_login(httpd_req_t *req) {
  char client_ip[64] = {0};
  get_client_ip(req, client_ip, sizeof(client_ip));

  int64_t now = esp_timer_get_time() / 1000000;

  if (s_login_rate_limit_mutex) {
    if (xSemaphoreTake(s_login_rate_limit_mutex, pdMS_TO_TICKS(500)) !=
        pdTRUE) {
      ESP_LOGE(TAG, "[MUTEX] login_rate_limit timeout in handle_api_login");
      return send_json(req, "{\"ok\":false,\"error\":\"server_busy\"}",
                       "503 Service Unavailable");
    }
  }

  login_rate_limit_t *rl = NULL;
  for (int i = 0; i < LOGIN_LRU_SIZE; i++) {
    if (s_rate_limits[i].ip[0] != '\0' &&
        strcmp(s_rate_limits[i].ip, client_ip) == 0) {
      rl = &s_rate_limits[i];
      break;
    }
  }

  if (!rl) {
    int evict_idx = 0;
    int64_t oldest = INT64_MAX;
    for (int i = 0; i < LOGIN_LRU_SIZE; i++) {
      if (s_rate_limits[i].ip[0] == '\0') {
        evict_idx = i;
        break;
      }
      if (s_rate_limits[i].last_seen < oldest) {
        oldest = s_rate_limits[i].last_seen;
        evict_idx = i;
      }
    }
    rl = &s_rate_limits[evict_idx];
    strlcpy(rl->ip, client_ip, sizeof(rl->ip));
    rl->attempts = 0;
    rl->block_until = 0;
  }

  rl->last_seen = now;

  int64_t block_until = rl->block_until;

  if (s_login_rate_limit_mutex) {
    xSemaphoreGive(s_login_rate_limit_mutex);
  }

  if (!is_same_origin(req, true)) {
    return send_json(req, "{\"ok\":false,\"error\":\"forbidden\"}",
                     "403 Forbidden");
  }

  if (block_until > now) {
    char resp[128];
    int remaining = (int)(block_until - now);
    snprintf(resp, sizeof(resp),
             "{\"ok\":false,\"error\":\"rate_limited\",\"retry_after\":%d}",
             remaining);
    return send_json(req, resp, "429 Too Many Requests");
  }

  char body[256] = {0};
  if (req->content_len >= sizeof(body)) {
    return send_json(req, "{\"ok\":false,\"error\":\"payload_too_large\"}",
                     "413 Request Entity Too Large");
  }
  if (!read_request_body(req, body, sizeof(body))) {
    return send_json(req, "{\"ok\":false,\"error\":\"empty_body\"}",
                     "401 Unauthorized");
  }

  char username[64] = {0};
  char password[64] = {0};
  bool remember = false;

  const char *user_start = strstr(body, "username=");
  if (user_start) {
    user_start += 9;
    const char *user_end = strchr(user_start, '&');
    size_t len =
        user_end ? (size_t)(user_end - user_start) : strlen(user_start);
    if (len > sizeof(username) - 1)
      len = sizeof(username) - 1;
    char tmp[64] = {0};
    memcpy(tmp, user_start, len);
    url_decode(username, tmp);

    const char *pass_start = strstr(body, "password=");
    if (pass_start) {
      pass_start += 9;
      const char *pass_end = strchr(pass_start, '&');
      len = pass_end ? (size_t)(pass_end - pass_start) : strlen(pass_start);
      if (len > sizeof(password) - 1)
        len = sizeof(password) - 1;
      char tmp2[64] = {0};
      memcpy(tmp2, pass_start, len);
      url_decode(password, tmp2);
    }
  } else {
    cJSON *root = cJSON_Parse(body);
    if (root) {
      cJSON *u = cJSON_GetObjectItem(root, "username");
      cJSON *p = cJSON_GetObjectItem(root, "password");
      if (u && cJSON_IsString(u)) {
        strlcpy(username, u->valuestring, sizeof(username));
      }
      if (p && cJSON_IsString(p)) {
        strlcpy(password, p->valuestring, sizeof(password));
      }
      cJSON *r = cJSON_GetObjectItem(root, "remember");
      if (r && cJSON_IsTrue(r)) {
        remember = true;
      }
      cJSON_Delete(root);
    }
  }

  if (strlen(username) == 0 || strlen(password) == 0) {
    update_login_rate_limit(client_ip, now, false);
    return send_json(req, "{\"ok\":false,\"error\":\"missing_fields\"}",
                     "401 Unauthorized");
  }

  if (!is_valid_utf8_printable(username, sizeof(username)) ||
      !is_valid_utf8_printable(password, sizeof(password))) {
    return send_json(req, "{\"ok\":false,\"error\":\"invalid_input\"}",
                     "400 Bad Request");
  }

  char stored_user[64] = {0};
  char stored_pass[64] = {0};
  nvs_store_get_credentials(stored_user, sizeof(stored_user), stored_pass,
                            sizeof(stored_pass));

  if (strcmp(username, stored_user) != 0 ||
      strcmp(password, stored_pass) != 0) {
    ESP_LOGW(TAG, "Login failed");
    update_login_rate_limit(client_ip, now, false);
    return send_json(req, "{\"ok\":false,\"error\":\"invalid_credentials\"}",
                     "401 Unauthorized");
  }

  char token[SESSION_TOKEN_LEN] = {0};
  if (!session_create(username, client_ip, token)) {
    return send_json(req, "{\"ok\":false,\"error\":\"session_error\"}",
                     "500 Internal Server Error");
  }

  update_login_rate_limit(client_ip, now, true);

  cJSON *resp = cJSON_CreateObject();
  cJSON_AddBoolToObject(resp, "ok", true);
  cJSON_AddStringToObject(resp, "username", username);
  if (is_password_default()) {
    cJSON_AddBoolToObject(resp, "require_password_change", true);
  }
  char *json_str = cJSON_PrintUnformatted(resp);
  cJSON_Delete(resp);

  /* Cookie buffers — one for HttpOnly session token, one for JS-readable marker
   */
  char cookie_session[400];
  char cookie_marker[128];

  if (remember) {
    snprintf(cookie_session, sizeof(cookie_session),
             "session=%s; Path=/; HttpOnly; SameSite=Lax; Max-Age=31536000",
             token);
    snprintf(cookie_marker, sizeof(cookie_marker),
             "logged_in=1; Path=/; SameSite=Lax; Max-Age=31536000");
  } else {
    snprintf(cookie_session, sizeof(cookie_session),
             "session=%s; Path=/; HttpOnly; SameSite=Lax", token);
    snprintf(cookie_marker, sizeof(cookie_marker),
             "logged_in=1; Path=/; SameSite=Lax");
  }
  httpd_resp_set_hdr(req, "Set-Cookie", cookie_session);
  /* In ESP-IDF v6, httpd_resp_set_hdr appends headers instead of overwriting,
   * so this works */
  httpd_resp_set_hdr(req, "Set-Cookie", cookie_marker);

  ESP_LOGI(TAG, "Login success");
  esp_err_t result = send_json(req, json_str, "200 OK");
  free(json_str);
  return result;
}

