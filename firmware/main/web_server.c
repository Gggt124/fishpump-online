#define SSE_MAX_CLIENTS 3
static int s_sse_clients[SSE_MAX_CLIENTS];
static portMUX_TYPE s_sse_client_lock = portMUX_INITIALIZER_UNLOCKED;

static bool sse_register_client(int sockfd) {
  bool registered = false;
  taskENTER_CRITICAL(&s_sse_client_lock);
  for (size_t i = 0; i < SSE_MAX_CLIENTS; i++) {
    if (s_sse_clients[i] == sockfd) {
      taskEXIT_CRITICAL(&s_sse_client_lock);
      return true;
    }
  }
  for (size_t i = 0; i < SSE_MAX_CLIENTS; i++) {
    if (s_sse_clients[i] < 0) {
      s_sse_clients[i] = sockfd;
      registered = true;
      break;
    }
  }
  taskEXIT_CRITICAL(&s_sse_client_lock);
  return registered;
}

static void sse_unregister_client(int sockfd) {
  taskENTER_CRITICAL(&s_sse_client_lock);
  for (size_t i = 0; i < SSE_MAX_CLIENTS; i++) {
    if (s_sse_clients[i] == sockfd) {
      s_sse_clients[i] = -1;
    }
  }
  taskEXIT_CRITICAL(&s_sse_client_lock);
}

static size_t sse_active_client_count(void) {
  size_t count = 0;
  taskENTER_CRITICAL(&s_sse_client_lock);
  for (size_t i = 0; i < SSE_MAX_CLIENTS; i++) {
    if (s_sse_clients[i] >= 0) {
      count++;
    }
  }
  taskEXIT_CRITICAL(&s_sse_client_lock);
  return count;
}

static esp_err_t diagnostics_socket_open(httpd_handle_t server, int sockfd) {
  (void)server;
  taskENTER_CRITICAL(&s_web_diag_lock);
  s_web_diag.sessions_opened++;
  s_web_diag.active_sessions++;
  if (s_web_diag.active_sessions > s_web_diag.peak_active_sessions) {
    s_web_diag.peak_active_sessions = s_web_diag.active_sessions;
  }
  uint32_t active_sessions = s_web_diag.active_sessions;
  uint32_t sessions_opened = s_web_diag.sessions_opened;
  taskEXIT_CRITICAL(&s_web_diag_lock);

  ESP_LOGD(TAG, "[HTTP_SOCKET] event=open fd=%d active=%lu opened=%lu", sockfd,
           (unsigned long)active_sessions, (unsigned long)sessions_opened);
  return ESP_OK;
}

static void diagnostics_socket_close(httpd_handle_t server, int sockfd) {
  (void)server;
  sse_unregister_client(sockfd);
  int close_result = close(sockfd);
  int close_errno = errno;

  taskENTER_CRITICAL(&s_web_diag_lock);
  s_web_diag.sessions_closed++;
  if (s_web_diag.active_sessions > 0) {
    s_web_diag.active_sessions--;
  }
  uint32_t active_sessions = s_web_diag.active_sessions;
  uint32_t sessions_closed = s_web_diag.sessions_closed;
  taskEXIT_CRITICAL(&s_web_diag_lock);

  if (close_result != 0 && close_errno != EBADF) {
    ESP_LOGW(
        TAG,
        "[HTTP_SOCKET] event=close_failed fd=%d errno=%d active=%lu closed=%lu",
        sockfd, close_errno, (unsigned long)active_sessions,
        (unsigned long)sessions_closed);
  } else {
    ESP_LOGD(TAG, "[HTTP_SOCKET] event=close fd=%d active=%lu closed=%lu",
             sockfd, (unsigned long)active_sessions,
             (unsigned long)sessions_closed);
  }
}

